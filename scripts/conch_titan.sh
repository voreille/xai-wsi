#!/bin/bash
# README 2f on a second tile encoder: CONCH v1.5 tiles (512 px at 20x) and the TITAN slide
# encoder as a pretrained slide-encoder baseline, under the concept-bag protocol.
#
# Stages (each skips finished work, so the script can be rerun after a crash):
#   embed      tile (configs/tiling/tiling_512.yaml) + CONCH v1.5 + fp16 repack of the four
#              cohorts (scripts/tile_embed_cohort.sh), one queue per GPU
#   titan      TITAN slide embeddings -> <cohort dir>/wsi-embeddings/titan/slides.parquet, with the cosine to
#              MahmoodLab's released TCGA embeddings as an end-to-end check
#   probe      ridge on the CONCH slide mean and on TITAN, LUAD and LUSC conditions
#   sweep      SAE concept bags on CONCH (scripts/concept_sweep.sh): LUAD+LUSC SAEs, K x top-k,
#              probed for both conditions; set SEEDS / LATENTS / TOPK for the val pick's seeds
#   bootstrap  paired bootstraps -> $OUT/bootstrap/: vs the CONCH slide mean, SAE vs TITAN, and
#              against the H-optimus-1 slide mean and bags (same targets and cases)
# Choose settings on TCGA val only. VALPICK=<k..._top..> adds the val pick's seeds as a row.
#
# Writes $OUT/config.yaml: configs/training/pathway_cohorts.yaml with data.embedding conch-v1.5-fp16
# and the tile model's input_dim 768.
# Needs access to the gated MahmoodLab/TITAN repo (CONCH v1.5 ships with it).
#
# Usage (on the host, from the repo root):
#   GPUS="0 1" TILE_WORKERS=8 bash scripts/conch_titan.sh
#   STAGES="bootstrap" VALPICK=k1024_top64 bash scripts/conch_titan.sh
#   STAGES="sweep bootstrap" LATENTS=1024 TOPK=64 SEEDS="1 2 3 4" VALPICK=k1024_top64 bash scripts/conch_titan.sh
set -euo pipefail

STAGES=${STAGES:-"embed titan probe sweep bootstrap"}
GPUS=${GPUS:-"0"}
TILE_WORKERS=${TILE_WORKERS:-4}
OUT=${OUT:-outputs/conch_titan}
EMBEDDING=conch-v1.5-fp16
SAE_COHORTS=${SAE_COHORTS:-"tcga-luad,tcga-lusc"}
LATENTS=${LATENTS:-"1024 4096 16384"}
TOPK=${TOPK:-"16 32 64"}
SEEDS=${SEEDS:-"0"}
VALPICK=${VALPICK:-}
CONFIG=$OUT/config.yaml

# cohort|slides root|rglob|include list (as in the H-optimus-1 tiling)
COHORTS=(
    "tcga-luad|/mnt/nas7/data/TCGA_Lung_svs/LUAD|*DX*.svs|"
    "tcga-lusc|/mnt/nas7/data/TCGA_Lung_svs/LUSC|*DX*.svs|"
    "cptac-luad|/mnt/nas6/data/CPTAC/CPTAC-LUAD_v12/LUAD|*.svs|data/processed/cptac-luad/metadata/slide_filenames.json"
    "cptac-lusc|/mnt/nas6/data/CPTAC/CPTAC-LSCC_v10/LSCC|*.svs|data/processed/cptac-lusc/metadata/slide_filenames.json"
)
NAMES="tcga-luad tcga-lusc cptac-luad cptac-lusc"

mkdir -p "$OUT/logs" "$OUT/bootstrap"
uv run python - "$CONFIG" <<'EOF'
import sys, yaml
config = yaml.safe_load(open("configs/training/pathway_cohorts.yaml"))
config["data"]["init_args"]["embedding"] = "conch-v1.5-fp16"
config["model"]["predictor"]["init_args"]["input_dim"] = 768
open(sys.argv[1], "w").write(
    "# Generated by scripts/conch_titan.sh from configs/training/pathway_cohorts.yaml.\n" + yaml.safe_dump(config, sort_keys=False)
)
EOF

read -r -a gpus <<< "$GPUS"
first_gpu=${gpus[0]}

if [[ " $STAGES " == *" embed "* ]]; then
    pids=()
    for g in "${!gpus[@]}"; do
        (
            failed=0
            for j in "${!COHORTS[@]}"; do
                (( j % ${#gpus[@]} == g )) || continue
                IFS='|' read -r cohort slides rglob include <<< "${COHORTS[$j]}"
                echo "embed $cohort on GPU ${gpus[$g]}"
                MODEL=conch-v1.5 TILES_GRID=512px TILING_CONFIG=configs/tiling/tiling_512.yaml \
                    COHORT=$cohort SLIDES=$slides RGLOB=$rglob INCLUDE_SLIDES=$include GPU=${gpus[$g]} \
                    TILE_WORKERS=$TILE_WORKERS bash scripts/tile_embed_cohort.sh \
                    > "$OUT/logs/embed_$cohort.log" 2>&1 \
                    || { echo "FAIL embed $cohort, see $OUT/logs/embed_$cohort.log"; failed=1; }
            done
            exit $failed
        ) &
        pids+=($!)
    done
    status=0
    for pid in "${pids[@]}"; do wait "$pid" || status=1; done
    (( status == 0 )) || exit 1
fi

if [[ " $STAGES " == *" titan "* ]]; then
    missing=()
    for cohort in $NAMES; do
        [[ -f data/processed/$cohort/wsi-embeddings/titan/slides.parquet ]] || missing+=("$cohort")
    done
    if (( ${#missing[@]} )); then
        echo "titan ${missing[*]}"
        # shellcheck disable=SC2086
        CUDA_VISIBLE_DEVICES=$first_gpu uv run python -m xaiwsi.concepts.titan \
            --config "$CONFIG" --cohorts "${missing[@]}" --reference --check-dir "$OUT/titan_check" 2>&1 | tee "$OUT/logs/titan.log" | grep "^\["
    fi
fi

if [[ " $STAGES " == *" probe "* ]]; then
    echo "probe slide mean + TITAN"
    uv run python -m xaiwsi.evaluation.cohort_probe \
        --config "$CONFIG" --conditions tcga-luad tcga-lusc \
        --features slide-mean "table:wsi-embeddings/titan/slides.parquet" \
        --output-dir "$OUT/probe" > "$OUT/logs/probe.log" 2>&1
fi

if [[ " $STAGES " == *" sweep "* ]]; then
    for side in luad lusc; do
        if [[ $side == luad ]]; then probe_cohorts="tcga-luad cptac-luad"; else probe_cohorts="tcga-lusc cptac-lusc"; fi
        CONFIG=$CONFIG TRAIN_COHORT_SETS="$SAE_COHORTS" LATENTS="$LATENTS" TOPK="$TOPK" SEEDS="$SEEDS" \
            CONDITION=tcga-$side PROBE_COHORTS="$probe_cohorts" GPUS="$GPUS" \
            OUT_ROOT="$OUT/sweep_$side" bash scripts/concept_sweep.sh
        uv run python -m xaiwsi.evaluation.collect_concept_runs --sweep-dir "$OUT/sweep_$side" \
            --sae-root "data/processed/sae/$EMBEDDING" --output "$OUT/sweep_$side/summary"
    done
fi

if [[ " $STAGES " == *" bootstrap "* ]]; then
    sae_name="${SAE_COHORTS//,/+}"
    for side in luad lusc; do
        condition=tcga-$side
        if [[ $side == luad ]]; then
            hopt_mean=outputs/concept_sweep/tcga-luad_k1024_top64_s0/predictions/tcga-luad__per_cohort.parquet
            hopt_sae='hopt-sae-luad+lusc-9=outputs/concept_sweep/tcga-luad+tcga-lusc_k*_s0/predictions/tcga-luad__per_cohort__table-concepts-tcga-luad+tcga-lusc_k*_s0-slides_mean__min0_clip.parquet'
            pairs="cptac-luad:test tcga-luad:val"
        else
            hopt_mean=outputs/concept_sweep_lusc/tcga-lusc_k1024_top32_s0/predictions/tcga-lusc__per_cohort.parquet
            hopt_sae='hopt-sae-luad+lusc-9=outputs/concept_sweep_lusc/tcga-luad+tcga-lusc_k*_s0/predictions/tcga-lusc__per_cohort__table-concepts-tcga-luad+tcga-lusc_k*_s0-slides_mean__min0_clip.parquet'
            pairs="cptac-lusc:test tcga-lusc:val"
        fi
        mean="conch-slide-mean=$OUT/probe/predictions/${condition}__per_cohort.parquet"
        titan="titan=$OUT/probe/predictions/${condition}__per_cohort__table-wsi-embeddings-titan-slides.parquet"
        sae="conch-sae-9=$OUT/sweep_$side/${sae_name}_k*_s0/predictions/${condition}__per_cohort__bags-${sae_name}_k*_s0-slides_mean__min0_clip.parquet"
        candidates=("$titan" "$sae")
        if [[ -n $VALPICK ]]; then
            candidates+=("conch-sae-valpick=$OUT/sweep_$side/${sae_name}_${VALPICK}_s[0-9]/predictions/${condition}__per_cohort__bags-${sae_name}_${VALPICK}_s[0-9]-slides_mean__min0_clip.parquet")
        fi
        for pair in $pairs; do
            cohort=${pair%%:*}
            split=${pair#*:}
            common=(--cohort "$cohort" --split "$split")
            uv run python -m xaiwsi.evaluation.paired_bootstrap --baseline "$mean" \
                --candidates "${candidates[@]}" "${common[@]}" --output "$OUT/bootstrap/vs_mean_$cohort"
            uv run python -m xaiwsi.evaluation.paired_bootstrap --baseline "$titan" \
                --candidates "${candidates[@]:1}" "${common[@]}" --output "$OUT/bootstrap/sae_vs_titan_$cohort"
            uv run python -m xaiwsi.evaluation.paired_bootstrap --baseline "hopt-slide-mean=$hopt_mean" \
                --candidates "$mean" "${candidates[@]}" "$hopt_sae" "${common[@]}" \
                --output "$OUT/bootstrap/vs_hopt_mean_$cohort"
        done
    done
fi
