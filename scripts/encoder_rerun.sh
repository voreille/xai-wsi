#!/bin/bash
# README 2f on another tile encoder (default UNI2-h) on the existing 224px tiles, in two phases,
# so the prediction from the training-only diagnostics is written down before any CPTAC result.
#
# Hypothesis (README 2f, after CONCH v1.5): SAE concept bags help when the encoder spreads the
# domain over many directions and the SAE keeps gaining from a larger dictionary
# (superposition); on an effectively low-rank encoder they reduce to a rotation and don't help.
#
# Phase A (TCGA only, no test cohort):
#   embed      CUDA embedding + fp16 repack of COHORTS (scripts/tile_embed_cohort.sh), one queue per GPU
#   spectrum   PCA spectrum of the tile stores vs H-optimus-1 and CONCH v1.5 (xaiwsi.evaluation.tile_spectrum)
#   capacity   train the LUAD+LUSC SAEs only (K x top-k grid) and tabulate FVU / live latents vs K
#              (xaiwsi.evaluation.sae_capacity)
# Phase B (after the prediction is recorded):
#   embed      with COHORTS="cptac-luad cptac-lusc"
#   probe      ridge on the slide mean, LUAD and LUSC conditions
#   sweep      bags + probes of the same SAEs (scripts/concept_sweep.sh; trained SAEs are reused)
#   bootstrap  paired bootstraps -> $OUT/bootstrap/: vs this encoder's and H-optimus-1's slide mean
#
# The grid is the H-optimus-1 one (K 1024/4096/16384 x top-k 16/32/64, both 1536-d), fixed in advance.
# Writes $OUT/config.yaml: configs/training/pathway_cohorts.yaml with data.embedding <MODEL>-fp16.
#
# Usage (on the host, from the repo root):
#   # phase A, TCGA (the two cohorts in parallel on two GPUs):
#   GPUS="0 1" COHORTS="tcga-luad tcga-lusc" STAGES="embed spectrum capacity" bash scripts/encoder_rerun.sh
#   # phase B, CPTAC and the probes:
#   GPUS="0 1" COHORTS="cptac-luad cptac-lusc" STAGES="embed probe sweep bootstrap" bash scripts/encoder_rerun.sh
set -euo pipefail

MODEL=${MODEL:-uni2-h}
DIM=${DIM:-1536}
STAGES=${STAGES:-"embed spectrum capacity"}
COHORTS=${COHORTS:-"tcga-luad tcga-lusc"}
GPUS=${GPUS:-"0"}
NUM_WORKERS=${NUM_WORKERS:-8}
BATCH_SIZE=${BATCH_SIZE:-256}
OUT=${OUT:-outputs/encoders/$MODEL}
EMBEDDING=$MODEL-fp16
SAE_COHORTS=${SAE_COHORTS:-"tcga-luad,tcga-lusc"}
LATENTS=${LATENTS:-"1024 4096 16384"}
TOPK=${TOPK:-"16 32 64"}
SEEDS=${SEEDS:-"0"}
CONFIG=$OUT/config.yaml

# cohort -> slides root of its 224px tiling (relative_wsi_path is relative to it)
declare -A SLIDES=(
    [tcga-luad]=/mnt/nas7/data/TCGA_Lung_svs/LUAD
    [tcga-lusc]=/mnt/nas7/data/TCGA_Lung_svs/LUSC
    [cptac-luad]=/mnt/nas6/data/CPTAC/CPTAC-LUAD_v12/LUAD
    [cptac-lusc]=/mnt/nas6/data/CPTAC/CPTAC-LSCC_v10/LSCC
)

mkdir -p "$OUT/logs" "$OUT/bootstrap"
uv run python - "$CONFIG" "$EMBEDDING" "$DIM" <<'EOF'
import sys, yaml
config = yaml.safe_load(open("configs/training/pathway_cohorts.yaml"))
config["data"]["init_args"]["embedding"] = sys.argv[2]
config["model"]["predictor"]["init_args"]["input_dim"] = int(sys.argv[3])
open(sys.argv[1], "w").write(
    "# Generated by scripts/encoder_rerun.sh from configs/training/pathway_cohorts.yaml.\n"
    + yaml.safe_dump(config, sort_keys=False)
)
EOF

read -r -a gpus <<< "$GPUS"
read -r -a cohorts <<< "$COHORTS"

if [[ " $STAGES " == *" embed "* ]]; then
    pids=()
    for g in "${!gpus[@]}"; do
        (
            failed=0
            for j in "${!cohorts[@]}"; do
                (( j % ${#gpus[@]} == g )) || continue
                cohort=${cohorts[$j]}
                echo "embed $cohort with $MODEL on GPU ${gpus[$g]}"
                MODEL=$MODEL TILES_GRID=224px COHORT=$cohort SLIDES=${SLIDES[$cohort]} STAGES="embed repack" \
                    GPU=${gpus[$g]} NUM_WORKERS=$NUM_WORKERS BATCH_SIZE=$BATCH_SIZE \
                    bash scripts/tile_embed_cohort.sh > "$OUT/logs/embed_$cohort.log" 2>&1 \
                    || { echo "FAIL embed $cohort, see $OUT/logs/embed_$cohort.log"; failed=1; }
            done
            exit $failed
        ) &
        pids+=($!)
    done
    status=0
    for pid in "${pids[@]}"; do wait "$pid" || status=1; done
    (( status == 0 )) || exit 1
fi

if [[ " $STAGES " == *" spectrum "* ]]; then
    stores=()
    for cohort in tcga-luad tcga-lusc; do
        for store in "$EMBEDDING" h-optimus-1-fp16 conch-v1.5-fp16; do
            stores+=("data/processed/$cohort/wsi-embeddings/$store")
        done
    done
    uv run python -m xaiwsi.evaluation.tile_spectrum --slides 200 --stores "${stores[@]}" \
        --output "$OUT/tile_spectrum"
fi

if [[ " $STAGES " == *" capacity "* ]]; then
    CONFIG=$CONFIG TRAIN_COHORT_SETS="$SAE_COHORTS" LATENTS="$LATENTS" TOPK="$TOPK" SEEDS="$SEEDS" \
        STEPS="train" GPUS="$GPUS" OUT_ROOT="$OUT/sweep_luad" bash scripts/concept_sweep.sh
    uv run python -m xaiwsi.evaluation.sae_capacity --stores "$EMBEDDING" h-optimus-1-fp16 conch-v1.5-fp16 \
        --train-cohorts "${SAE_COHORTS//,/+}" --output "$OUT/sae_capacity"
fi

if [[ " $STAGES " == *" probe "* ]]; then
    echo "probe slide mean"
    uv run python -m xaiwsi.evaluation.cohort_probe --config "$CONFIG" --conditions tcga-luad tcga-lusc \
        --features slide-mean --output-dir "$OUT/probe" > "$OUT/logs/probe.log" 2>&1
fi

if [[ " $STAGES " == *" sweep "* ]]; then
    for side in luad lusc; do
        if [[ $side == luad ]]; then probe_cohorts="tcga-luad cptac-luad"; else probe_cohorts="tcga-lusc cptac-lusc"; fi
        CONFIG=$CONFIG TRAIN_COHORT_SETS="$SAE_COHORTS" LATENTS="$LATENTS" TOPK="$TOPK" SEEDS="$SEEDS" \
            CONDITION=tcga-$side PROBE_COHORTS="$probe_cohorts" GPUS="$GPUS" \
            OUT_ROOT="$OUT/sweep_$side" bash scripts/concept_sweep.sh
        uv run python -m xaiwsi.evaluation.collect_concept_runs --sweep-dir "$OUT/sweep_$side" \
            --sae-root "models/sae/$EMBEDDING" --output "$OUT/sweep_$side/summary"
    done
fi

if [[ " $STAGES " == *" bootstrap "* ]]; then
    sae_name="${SAE_COHORTS//,/+}"
    for side in luad lusc; do
        condition=tcga-$side
        if [[ $side == luad ]]; then
            hopt_mean=outputs/concept_sweep/tcga-luad_k1024_top64_s0/predictions/tcga-luad__per_cohort.parquet
            hopt_sae='hopt-sae-luad+lusc-9=outputs/concept_sweep/tcga-luad+tcga-lusc_k*_s0/predictions/tcga-luad__per_cohort__table-concepts-tcga-luad+tcga-lusc_k*_s0-slides_mean__min0_clip.parquet'
            pairs="cptac-luad:test tcga-luad:val"
        else
            hopt_mean=outputs/concept_sweep_lusc/tcga-lusc_k1024_top32_s0/predictions/tcga-lusc__per_cohort.parquet
            hopt_sae='hopt-sae-luad+lusc-9=outputs/concept_sweep_lusc/tcga-luad+tcga-lusc_k*_s0/predictions/tcga-lusc__per_cohort__table-concepts-tcga-luad+tcga-lusc_k*_s0-slides_mean__min0_clip.parquet'
            pairs="cptac-lusc:test tcga-lusc:val"
        fi
        mean="$MODEL-slide-mean=$OUT/probe/predictions/${condition}__per_cohort.parquet"
        grid=()
        for latents in $LATENTS; do for k in $TOPK; do
            grid+=("$OUT/sweep_$side/${sae_name}_k${latents}_top${k}_s0/predictions/${condition}__per_cohort__bags-${sae_name}_k${latents}_top${k}_s0-slides_mean__min0_clip.parquet")
        done; done
        for f in "${grid[@]}"; do [[ -f $f ]] || { echo "missing $f"; exit 1; }; done
        # the encoder's sweep folder holds only the fixed grid, so one glob covers it
        sae="$MODEL-sae-grid=$OUT/sweep_$side/${sae_name}_k*_s0/predictions/${condition}__per_cohort__bags-${sae_name}_k*_s0-slides_mean__min0_clip.parquet"
        for pair in $pairs; do
            cohort=${pair%%:*}
            split=${pair#*:}
            uv run python -m xaiwsi.evaluation.paired_bootstrap --baseline "hopt-slide-mean=$hopt_mean" \
                --candidates "$mean" "$sae" "$hopt_sae" \
                --cohort "$cohort" --split "$split" --output "$OUT/bootstrap/vs_hopt_mean_$cohort"
            uv run python -m xaiwsi.evaluation.paired_bootstrap --baseline "$mean" \
                --candidates "$sae" --cohort "$cohort" --split "$split" --output "$OUT/bootstrap/vs_mean_$cohort"
        done
    done
fi
