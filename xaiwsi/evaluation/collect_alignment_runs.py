"""Collect WSI <-> RNA alignment runs (scripts/alignment_sweep.sh) into one table.

For each run directory ``<run-root>/<prefix>-*``: slide encoder, tile dropout, weight
decay and seed from its ``config.yaml``; best val ``mean_mrr`` and its epoch from the
ModelCheckpoint state of the best checkpoint; CPTAC retrieval from ``test_metrics.json``.
Runs without ``test_metrics.json`` are listed and skipped.

    uv run python -m xaiwsi.evaluation.collect_alignment_runs \\
        --run-root runs/alignment/xai-wsi --prefix aln-1025 --output-dir outputs/alignment_runs

Writes ``alignment_runs.csv`` (one row per run) and ``alignment_runs.md`` (mean and sd
over seeds per setting, with the generating command).
"""

from __future__ import annotations

import argparse
import json
import re
import shlex
import sys
from pathlib import Path

import pandas as pd
import torch
import yaml

from xaiwsi.evaluation.cohort_probe import markdown_table

TEST_METRICS = ["wsi2rna_r5", "wsi2rna_mrr", "rna2wsi_r5", "rna2wsi_mrr", "mean_mrr"]


def best_checkpoint_state(run_dir: Path) -> tuple[float, int]:
    """(best val score, epoch) from the best `epoch=*.ckpt`."""
    ckpts = sorted((run_dir / "checkpoints").glob("epoch=*.ckpt"))
    if len(ckpts) != 1:
        raise SystemExit(f"{run_dir}: expected one epoch=*.ckpt, found {[c.name for c in ckpts]}.")
    state = torch.load(ckpts[0], map_location="cpu", weights_only=False)
    scores = [
        v["best_model_score"]
        for k, v in state.get("callbacks", {}).items()
        if k.startswith("ModelCheckpoint") and v.get("best_model_score") is not None
    ]
    if len(scores) != 1:
        raise SystemExit(f"{ckpts[0]}: expected one ModelCheckpoint best score, found {len(scores)}.")
    epoch = int(re.match(r"epoch=(\d+)", ckpts[0].name).group(1))
    return float(scores[0]), epoch


def run_row(run_dir: Path) -> dict:
    config = yaml.safe_load((run_dir / "config.yaml").read_text())
    aligner = config["model"]["aligner"]["init_args"]
    encoder = aligner["slide_encoder"]
    val_mrr, epoch = best_checkpoint_state(run_dir)
    test = json.loads((run_dir / "test_metrics.json").read_text())["metrics"]
    return {
        "run": run_dir.name,
        "encoder": encoder["class_path"].rsplit(".", 1)[-1],
        "tile_dropout": encoder["init_args"].get("tile_dropout", 0.0),
        "weight_decay": config["model"]["weight_decay"],
        "seed": config["seed_everything"],
        "best_epoch": epoch,
        "val_mean_mrr": val_mrr,
        **{f"test_{name}": test[name] for name in TEST_METRICS},
    }


def check_ranges(runs: pd.DataFrame) -> None:
    columns = ["val_mean_mrr"] + [f"test_{name}" for name in TEST_METRICS]
    values = runs[columns]
    if ((values < 0) | (values > 1)).any().any():
        raise ValueError(f"Recall/MRR outside [0, 1]:\n{runs}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run-root", type=Path, required=True)
    parser.add_argument("--prefix", required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()

    rows = []
    for run_dir in sorted(args.run_root.glob(f"{args.prefix}-*")):
        if not (run_dir / "test_metrics.json").exists():
            print(f"skip {run_dir.name}: no test_metrics.json")
            continue
        rows.append(run_row(run_dir))
    if not rows:
        raise SystemExit(f"No finished runs under {args.run_root}/{args.prefix}-*.")
    runs = pd.DataFrame(rows)
    check_ranges(runs)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    runs.to_csv(args.output_dir / "alignment_runs.csv", index=False)

    keys = ["encoder", "tile_dropout", "weight_decay"]
    metrics = ["best_epoch", "val_mean_mrr"] + [f"test_{name}" for name in TEST_METRICS]
    grouped = runs.groupby(keys)
    summary = grouped[metrics].agg(["mean", "std"])
    summary.columns = [f"{m}_{s}" for m, s in summary.columns]
    summary.insert(0, "n_runs", grouped.size())
    summary = summary.reset_index()
    command = "uv run python -m xaiwsi.evaluation.collect_alignment_runs " + shlex.join(sys.argv[1:])
    table = markdown_table(summary)
    (args.output_dir / "alignment_runs.md").write_text(
        "Alignment runs, mean and sd over seeds; val = TCGA-LUAD val at the best checkpoint, "
        f"test = CPTAC-LUAD. Generated by:\n\n```bash\n{command}\n```\n\n{table}\n"
    )
    print(table)


if __name__ == "__main__":
    main()
