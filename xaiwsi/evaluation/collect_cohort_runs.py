"""Collect tile-level multi-cohort runs (scripts/pathway_cohorts.sh) into one table.

For each run directory `<run-root>/<prefix>-*`: training cohorts and target normalization
from the saved config, the best validation score from the checkpoint's ModelCheckpoint
state (the config's monitor, TCGA-LUAD val median Spearman), and per-cohort test metrics
from `test_metrics.json`. Values are range-checked.

    uv run python -m xaiwsi.evaluation.collect_cohort_runs \\
        --run-root runs/pathways/xai-wsi --prefix coh-1023 --output-dir outputs/cohort_runs

Writes `cohort_runs.csv` (one row per run and test cohort), and `cohort_runs.md` (mean and
sd over seeds per condition, with the generating command, for progress.md).
"""

from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path

import pandas as pd
import yaml

from xaiwsi.evaluation.cohort_probe import markdown_table
from xaiwsi.evaluation.collect_learning_curve import best_val_score
from xaiwsi.training.run_config import data_args


def check_ranges(results: pd.DataFrame) -> None:
    for column in ("val_median_spearman", "test_median_spearman", "test_mean_spearman"):
        values = results[column].dropna()
        if ((values < -1) | (values > 1)).any():
            raise ValueError(f"{column} outside [-1, 1]:\n{results}")
    if (results["test_median_r2"].dropna() > 1).any():
        raise ValueError(f"R² above 1:\n{results}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run-root", type=Path, default=Path("runs/pathways/xai-wsi"))
    parser.add_argument("--prefix", required=True)
    parser.add_argument("--output-dir", type=Path, default=Path("outputs/cohort_runs"))
    args = parser.parse_args()

    rows = []
    for run_dir in sorted(args.run_root.glob(f"{args.prefix}-*")):
        config = yaml.safe_load((run_dir / "config.yaml").read_text())
        data = data_args(config)
        train = data.get("use_train_cohorts") or [c["name"] for c in data["train_cohorts"]]
        metrics_path = run_dir / "test_metrics.json"
        if not metrics_path.exists():
            raise SystemExit(f"{metrics_path} is missing: run the test stage first.")
        metrics = json.loads(metrics_path.read_text())
        for cohort, entry in metrics["cohorts"].items():
            summary = entry["summary"]
            rows.append(
                {
                    "run": run_dir.name,
                    "train_cohorts": "+".join(train),
                    "normalization": data.get("target_normalization", "per_cohort"),
                    "seed": config.get("seed_everything"),
                    "val_median_spearman": best_val_score(run_dir),
                    "test_cohort": cohort,
                    "n_test": entry["n_cases"],
                    "test_median_spearman": summary["median_spearman"],
                    "test_mean_spearman": summary["mean_spearman"],
                    "test_median_r2": summary["median_r2"],
                }
            )
    if not rows:
        raise SystemExit(f"No runs matching {args.run_root}/{args.prefix}-*")

    results = pd.DataFrame(rows)
    check_ranges(results)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    results.to_csv(args.output_dir / "cohort_runs.csv", index=False)

    metrics = ["val_median_spearman", "test_median_spearman", "test_median_r2"]
    grouped = results.groupby(["train_cohorts", "normalization", "test_cohort"])
    summary = grouped[metrics].agg(["mean", "std"])
    summary.columns = [f"{m}_{stat}" for m, stat in summary.columns]
    summary.insert(0, "n_runs", grouped.size())
    summary = summary.reset_index()

    command = "uv run python -m xaiwsi.evaluation.collect_cohort_runs " + shlex.join(sys.argv[1:])
    table = markdown_table(summary)
    (args.output_dir / "cohort_runs.md").write_text(
        f"Tile-level runs, mean and sd over seeds. Generated by:\n\n```bash\n{command}\n```\n\n{table}\n"
    )
    with pd.option_context("display.width", 200):
        print(results.to_string(index=False))
    print(table)
    print(f"Output: {args.output_dir}")


if __name__ == "__main__":
    main()
