"""Where the cohort shift sits: SAE reconstruction vs residual of the slide means.

For each SAE (``xaiwsi.concepts.residual`` tables) and a pair of cohorts (reference, shifted),
compares three slide representations in the SAE's normalised space: the slide mean
(``recon + residual``), the reconstructed part ``ā D + b_pre`` and the mean residual ``r̄``.
Per part:

- ``shift``: norm of the difference of cohort means. The mean's shift vector is the sum of the
  two parts' shift vectors, so ``shift_share`` (part shift / mean shift) says where it sits.
- ``shift_to_spread``: squared shift over the reference cohort's total variance of that part
  (scale-free, so the parts compare despite different sizes).
- ``domain_auc``: 5-fold CV ROC AUC of an L2 logistic regression (standardised features)
  separating the cohorts.

    uv run python -m xaiwsi.evaluation.concept_shift --reference data/processed/tcga-luad \\
        --shifted data/processed/cptac-luad --sae-names tcga-luad_k4096_top32_s0 \\
        --output outputs/concept_residual/shift_luad

Writes ``<output>.csv`` and ``<output>.md`` (with the generating command).
"""

from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from xaiwsi.evaluation.cohort_probe import markdown_table


def load_parts(cohort_dir: Path, name: str) -> dict[str, np.ndarray]:
    recon = pd.read_parquet(cohort_dir / "concepts" / name / "slides_recon.parquet")
    residual = pd.read_parquet(cohort_dir / "concepts" / name / "slides_residual.parquet")
    residual = residual.loc[recon.index]
    return {
        "mean": (recon + residual).to_numpy(np.float64),
        "recon": recon.to_numpy(np.float64),
        "residual": residual.to_numpy(np.float64),
    }


def domain_auc(x_ref: np.ndarray, x_shift: np.ndarray, c: float, seed: int) -> float:
    x = np.concatenate([x_ref, x_shift])
    y = np.r_[np.zeros(len(x_ref)), np.ones(len(x_shift))]
    model = make_pipeline(StandardScaler(), LogisticRegression(C=c, max_iter=2000))
    folds = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
    scores = cross_val_predict(model, x, y, cv=folds, method="decision_function")
    return float(roc_auc_score(y, scores))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--reference", type=Path, required=True, help="reference cohort dir (SAE training cohort)")
    parser.add_argument("--shifted", type=Path, required=True, help="shifted cohort dir")
    parser.add_argument("--sae-names", nargs="+", required=True, help="bag folder names under concepts/")
    parser.add_argument("--c", type=float, default=1e-3, help="inverse L2 strength of the domain classifier")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)

    rows = []
    for name in args.sae_names:
        ref, shifted = load_parts(args.reference, name), load_parts(args.shifted, name)
        mean_shift = np.linalg.norm(shifted["mean"].mean(0) - ref["mean"].mean(0))
        for part in ("mean", "recon", "residual"):
            delta = shifted[part].mean(0) - ref[part].mean(0)
            shift = float(np.linalg.norm(delta))
            auc = domain_auc(ref[part], shifted[part], args.c, args.seed)
            if not 0 <= auc <= 1:
                raise ValueError(f"AUC out of range for {name} {part}: {auc}")
            rows.append(
                {
                    "sae": name,
                    "part": part,
                    "n_reference": len(ref[part]),
                    "n_shifted": len(shifted[part]),
                    "shift": shift,
                    "shift_share": shift / mean_shift,
                    "shift_to_spread": shift**2 / ref[part].var(axis=0).sum(),
                    "domain_auc": auc,
                }
            )
            print(f"{name} {part}: shift {shift:.3f} share {shift / mean_shift:.2f} AUC {auc:.3f}")

    results = pd.DataFrame(rows)
    results.to_csv(args.output.with_suffix(".csv"), index=False)
    command = "uv run python -m xaiwsi.evaluation.concept_shift " + shlex.join(sys.argv[1:])
    args.output.with_suffix(".md").write_text(
        f"Cohort shift of the slide mean and its SAE parts ({args.reference.name} -> {args.shifted.name}). "
        f"Generated by:\n\n```bash\n{command}\n```\n\n{markdown_table(results)}\n"
    )
    print(f"Output: {args.output}")


if __name__ == "__main__":
    main()
