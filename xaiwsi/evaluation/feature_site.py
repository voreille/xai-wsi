"""Site shortcut of slide representations: TCGA tissue-source-site probe on slide feature tables.

The same probe as ``xaiwsi.evaluation.shared_structure`` (5-fold CV logistic regression,
balanced accuracy, sites with at least ``--min-site-cases`` cases) on the train + val cases of
one training cohort (split of a ``CohortPathwayDataModule`` config). Features use the syntax of
``xaiwsi.evaluation.cohort_probe --features``: ``slide-mean`` or ``table:<parquet relative to the
cohort dir>``, ``+``-joined.

    uv run python -m xaiwsi.evaluation.feature_site --config configs/training/pathway_cohorts.yaml \\
        --cohort tcga-luad \\
        --features slide-mean table:concepts/tcga-luad_k4096_top32/slides_mean.parquet \\
        --output outputs/concept_probe/site_tcga-luad

Writes ``<output>.csv`` and ``<output>.md`` (table with the generating command).
"""

from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from xaiwsi.data.cohorts import CohortSpec, build_pathway_splits, select_cohorts
from xaiwsi.evaluation.cohort_probe import markdown_table
from xaiwsi.evaluation.learning_curve import slide_means
from xaiwsi.evaluation.shared_structure import site_probe, tcga_site
from xaiwsi.rna.pathways.hallmarks import load_hallmarks
from xaiwsi.training.run_config import data_args


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--cohort", required=True, help="a TCGA training cohort of the config")
    parser.add_argument("--features", nargs="+", required=True)
    parser.add_argument("--min-site-cases", type=int, default=10)
    parser.add_argument("--slide-means-cache", type=Path, default=None, help="default: next to --output")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)

    data = data_args(yaml.safe_load(args.config.read_text()))
    processed_root, embedding = data.get("processed_root"), data.get("embedding", "h-optimus-1")
    train_specs = [CohortSpec(**s) for s in data["train_cohorts"]]
    test_specs = [CohortSpec(**s) for s in data["test_cohorts"]]
    train_used, _ = select_cohorts(train_specs, test_specs, [args.cohort])
    resolved = train_used[0].resolve(processed_root, embedding)
    splits = build_pathway_splits(
        [resolved],
        [],
        load_hallmarks(data["hallmark_gmt"]),
        val_fraction=data.get("val_fraction", 0.2),
        split_seed=data.get("split_seed", 42),
    )
    parts = splits["train"] + splits["val"]
    pairs = pd.concat([p.pairs for p in parts], ignore_index=True)
    slide_ids = pairs["slide_id"].astype(str)
    sites = tcga_site(pairs["case_id"]).to_numpy()
    cohort_dir = resolved.embedding_dir.parent.parent
    cache = args.slide_means_cache or args.output.parent / f"slide_means_{args.cohort}_{embedding}.parquet"

    rows = []
    for features in args.features:
        blocks = []
        for block in features.split("+"):
            if block == "slide-mean":
                table = slide_means(parts[0].store, sorted(set(slide_ids)), cache)
            elif block.startswith("table:"):
                table = pd.read_parquet(cohort_dir / block.removeprefix("table:"))
                table.index = table.index.astype(str)
            else:
                raise SystemExit(f"Unknown feature block {block!r}")
            blocks.append(table.loc[slide_ids].to_numpy())
        x = np.concatenate(blocks, axis=1)
        result = site_probe(x, sites, args.min_site_cases)
        if not 0 <= result["balanced_accuracy"] <= 1:
            raise ValueError(f"Balanced accuracy out of range: {result}")
        rows.append({"features": features, "n_features": x.shape[1], **result})
        print(f"{features}: balanced accuracy {result['balanced_accuracy']:.3f} (chance {result['chance']:.3f})")

    results = pd.DataFrame(rows)
    results.to_csv(args.output.with_suffix(".csv"), index=False)
    command = "uv run python -m xaiwsi.evaluation.feature_site " + shlex.join(sys.argv[1:])
    args.output.with_suffix(".md").write_text(
        f"TCGA site probe ({args.cohort} train + val, 5-fold CV balanced accuracy). Generated by:\n\n"
        f"```bash\n{command}\n```\n\n{markdown_table(results)}\n"
    )
    print(f"Output: {args.output}")


if __name__ == "__main__":
    main()
