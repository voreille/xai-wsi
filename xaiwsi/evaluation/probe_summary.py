"""Compact wide table of ridge-probe metrics, for progress.md.

Reads the ``probe_metrics.csv`` of ``cohort_probe`` / ``compartment_probe`` runs (one per
``<label>=<path>``), keeps one condition and normalization, and writes one row per label and
feature set with one column per split/cohort and metric.

    uv run python -m xaiwsi.evaluation.probe_summary \\
        Hallmarks=outputs/compartment_probe/probe_metrics.csv \\
        Tavernari=outputs/compartment_probe_tavernari/probe_metrics.csv \\
        --condition tcga-luad --output outputs/compartment_probe/summary_luad.md
"""

from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path

import pandas as pd

from xaiwsi.evaluation.cohort_probe import check_ranges, markdown_table


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("inputs", nargs="+", help="<label>=<probe_metrics.csv>")
    parser.add_argument("--condition", required=True)
    parser.add_argument("--normalization", default="per_cohort")
    parser.add_argument("--metrics", nargs="+", default=["median_spearman", "median_r2"])
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    frames = []
    for item in args.inputs:
        label, sep, path = item.partition("=")
        if not sep:
            raise SystemExit(f"expected <label>=<path>, got {item!r}")
        frame = pd.read_csv(path)
        if "features" not in frame:
            frame["features"] = "slide-mean"
        frame = frame[(frame["condition"] == args.condition) & (frame["normalization"] == args.normalization)]
        if frame.empty:
            raise SystemExit(f"{path}: no rows for {args.condition} / {args.normalization}")
        check_ranges(frame)
        frames.append(frame.assign(targets=label))
    results = pd.concat(frames, ignore_index=True)
    # The same feature set may come from several files (e.g. slide-mean); it must agree.
    keys = ["targets", "features", "split", "cohort"]
    spread = results.groupby(keys)[args.metrics].agg(lambda v: v.max() - v.min())
    if (spread > 1e-6).any().any():
        raise SystemExit(f"duplicated rows disagree:\n{spread[(spread > 1e-6).any(axis=1)]}")
    results = results.drop_duplicates(keys)

    wide = results.pivot_table(
        index=["targets", "features"], columns=["split", "cohort"], values=args.metrics, sort=False
    )
    wide = wide.reorder_levels([1, 2, 0], axis=1)
    split_order = {"val": 0, "test": 1}
    wide = wide[sorted(wide.columns, key=lambda c: (split_order.get(c[0], 2), c[1], args.metrics.index(c[2])))]
    wide.columns = [f"{split} {cohort} {metric.replace('median_', '')}" for split, cohort, metric in wide.columns]
    table = wide.reset_index()

    command = "uv run python -m xaiwsi.evaluation.probe_summary " + shlex.join(sys.argv[1:])
    text = (
        f"Ridge probes, condition {args.condition}, {args.normalization} (medians over targets). "
        f"Generated by:\n\n```bash\n{command}\n```\n\n{markdown_table(table)}\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
