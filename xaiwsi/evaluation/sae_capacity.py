"""SAE capacity per tile encoder: reconstruction error and dead latents against dictionary size.

Reads ``train.json`` of the SAEs under ``models/sae/<store>/`` (``xaiwsi.concepts.train_sae``) and
tabulates, per store, top-k and dictionary size K: val FVU, val dead fraction and live latents
(K x (1 - dead)). A representation with features in superposition keeps losing FVU as K grows
and keeps its latents alive; one that is effectively low-rank on the data flattens and the
extra latents die (README 2f, CONCH v1.5). Uses training data only, so it can be read before
any test cohort is encoded.

    uv run python -m xaiwsi.evaluation.sae_capacity --stores h-optimus-1-fp16 conch-v1.5-fp16 \\
        --train-cohorts tcga-luad+tcga-lusc --output outputs/encoders/sae_capacity

Writes ``<output>.csv`` and ``<output>.md`` (long table, and FVU / live latents as K x top-k grids
per store, with the generating command).
"""

from __future__ import annotations

import argparse
import json
import re
import shlex
import sys
from pathlib import Path

import pandas as pd

from xaiwsi.evaluation.cohort_probe import markdown_table
from xaiwsi.paths import model_dir

NAME = re.compile(r"^(?P<cohorts>.+)_k(?P<latents>\d+)_top(?P<k>\d+)_s(?P<seed>\d+)$")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stores", nargs="+", required=True)
    parser.add_argument("--train-cohorts", default="tcga-luad+tcga-lusc", help="SAE name prefix (cohorts joined by +)")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    rows = []
    for store in dict.fromkeys(args.stores):
        for path in sorted(model_dir("sae", store).glob("*/train.json")):
            m = NAME.match(path.parent.name)
            if not m or m["cohorts"] != args.train_cohorts or int(m["seed"]) != args.seed:
                continue
            final = json.loads(path.read_text())["final"]
            latents, dead = int(m["latents"]), float(final["dead_fraction_val"])
            fvu = float(final["val_fvu"])
            if not (0 <= dead <= 1 and fvu >= 0):
                raise ValueError(f"{path}: dead fraction {dead} or FVU {fvu} out of range")
            rows.append({"store": store, "latents": latents, "k": int(m["k"]), "val_fvu": fvu,
                         "dead_fraction_val": dead, "live_latents": round(latents * (1 - dead))})
    if not rows:
        raise SystemExit("no SAEs found")
    table = pd.DataFrame(rows).sort_values(["store", "k", "latents"]).reset_index(drop=True)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    table.to_csv(args.output.with_suffix(".csv"), index=False)
    command = "uv run python -m xaiwsi.evaluation.sae_capacity " + shlex.join(sys.argv[1:])
    text = f"SAE capacity ({args.train_cohorts}, seed {args.seed}; val split). Generated by:\n\n```bash\n{command}\n```\n"
    for store, block in table.groupby("store", sort=False):
        for value, label in (("val_fvu", "val FVU"), ("live_latents", "live latents")):
            grid = block.pivot(index="k", columns="latents", values=value)
            grid.columns = [f"K {c}" for c in grid.columns]
            text += f"\n{store}, {label} (rows top-k):\n\n{markdown_table(grid.round(3).reset_index())}\n"
    args.output.with_suffix(".md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
