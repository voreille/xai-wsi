"""Effective dimensionality of tile embedding stores (PCA spectrum on a tile sample).

Samples ``--slides`` slides and ``--tiles`` tiles per slide of each store, centres them and
reports the number of PCs for 80/90/97/99% of the variance, the numerical rank (singular
values above 1e-3 of the largest), the participation ratio
``(sum λ)² / sum λ²`` and the first eigenvalue's share. Used to compare tile encoders before
setting SAE sparsity (README 2f).

    uv run python -m xaiwsi.evaluation.tile_spectrum \\
        --stores data/processed/tcga-luad/wsi-embeddings/conch-v1.5-fp16 \\
        data/processed/tcga-luad/wsi-embeddings/h-optimus-1-fp16 --output outputs/conch_titan/tile_spectrum

Writes ``<output>.csv`` and ``<output>.md`` (with the generating command).
"""

from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from wsitools.storage.factory import build_embedding_store_from_dir

from xaiwsi.evaluation.cohort_probe import markdown_table
from xaiwsi.paths import cohort_name, store_name


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stores", type=Path, nargs="+", required=True)
    parser.add_argument("--slides", type=int, default=60)
    parser.add_argument("--tiles", type=int, default=300)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    rows = []
    for path in args.stores:
        rng = np.random.default_rng(args.seed)
        store = build_embedding_store_from_dir(root_dir=path)
        ids = sorted(store.slide_ids())
        picked = [ids[i] for i in rng.choice(len(ids), min(args.slides, len(ids)), replace=False)]
        blocks = []
        for slide_id in picked:
            tiles = np.asarray(store.load(slide_id)[0], dtype=np.float64)
            blocks.append(tiles[rng.choice(len(tiles), min(args.tiles, len(tiles)), replace=False)])
        x = np.concatenate(blocks)
        x -= x.mean(0)
        sv = np.linalg.svd(x, compute_uv=False)
        ev = sv**2 / np.sum(sv**2)
        cum = np.cumsum(ev)
        row = {"cohort": cohort_name(path), "store": store_name(path), "tiles": len(x), "dim": x.shape[1]}
        for q in (0.8, 0.9, 0.97, 0.99):
            row[f"pcs_{q:g}"] = int(np.searchsorted(cum, q)) + 1
        row["participation_ratio"] = float(1 / np.sum(ev**2))
        # numerical rank: singular values above 1e-3 of the largest (fp16 stores)
        row["rank_1e-3"] = int((sv > 1e-3 * sv[0]).sum())
        row["top1_share"] = float(ev[0])
        rows.append(row)

    table = pd.DataFrame(rows)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    table.to_csv(args.output.with_suffix(".csv"), index=False)
    command = "uv run python -m xaiwsi.evaluation.tile_spectrum " + shlex.join(sys.argv[1:])
    text = markdown_table(table.round(3))
    args.output.with_suffix(".md").write_text(
        f"PCA spectrum of tile embeddings ({args.slides} slides x {args.tiles} tiles, seed {args.seed}). "
        f"Generated by:\n\n```bash\n{command}\n```\n\n{text}\n"
    )
    print(text)


if __name__ == "__main__":
    main()
