"""Side-by-side test metrics of several tile-composition probe runs (``xaiwsi.tissue.probe`` outputs).

    uv run python -m xaiwsi.tissue.compare \\
        none=outputs/tissue_probe/anorak_ctx-none ring1=outputs/tissue_probe/anorak_ctx-ring1 \\
        --output outputs/tissue_probe/anorak_ctx

Reads each run's ``test_metrics.json`` and ``per_class.csv`` and writes ``<output>.csv``
(long: run, class, metric, value) and ``<output>.md``: summary metrics per run, and the
per-class ``--metric`` (default tile R²) with one column per run.
"""

from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path

import pandas as pd

from xaiwsi.evaluation.cohort_probe import markdown_table

SUMMARY = ["median_tile_r2", "median_tile_r", "median_mixed_r", "median_image_r", "pure_macro_f1", "soft_ce", "weight_decay"]
BOUNDED = {"tile_r": (-1, 1), "mixed_r": (-1, 1), "image_r": (-1, 1), "tile_r2": (float("-inf"), 1), "pure_f1": (0, 1)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("runs", nargs="+", help="<label>=<probe output dir>")
    parser.add_argument("--metric", default="tile_r2", help="per_class.csv column for the per-class table")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    summaries, per_class = {}, []
    for item in args.runs:
        label, sep, path = item.partition("=")
        if not sep:
            raise SystemExit(f"expected <label>=<dir>, got {item!r}")
        summaries[label] = json.loads((Path(path) / "test_metrics.json").read_text())
        frame = pd.read_csv(Path(path) / "per_class.csv")
        for column, (low, high) in BOUNDED.items():
            if column in frame and not frame[column].dropna().between(low, high).all():
                raise ValueError(f"{path}: {column} outside [{low}, {high}]")
        per_class.append(frame.melt(id_vars="class", var_name="metric").assign(run=label))
    long = pd.concat(per_class, ignore_index=True)[["run", "class", "metric", "value"]]
    summary = pd.DataFrame({label: {k: s.get(k) for k in SUMMARY} for label, s in summaries.items()}).T
    for column in ("median_tile_r2",):
        if (summary[column] > 1).any():
            raise ValueError(f"{column} above 1")
    wide = long[long["metric"] == args.metric].pivot(index="class", columns="run", values="value")
    wide = wide[list(summaries)].reindex(long["class"].drop_duplicates())

    args.output.parent.mkdir(parents=True, exist_ok=True)
    long.to_csv(f"{args.output}.csv", index=False)
    command = "uv run python -m xaiwsi.tissue.compare " + shlex.join(sys.argv[1:])
    text = (
        f"Tile-composition probes, test split. Generated by:\n\n```bash\n{command}\n```\n\n"
        f"{markdown_table(summary.rename_axis('run').reset_index())}\n\n"
        f"Per class, `{args.metric}`:\n\n{markdown_table(wide.rename_axis(None, axis=1).reset_index())}\n"
    )
    Path(f"{args.output}.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
